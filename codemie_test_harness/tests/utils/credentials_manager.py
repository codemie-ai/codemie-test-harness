    @staticmethod
    def google_oauth_credentials() -> List[CredentialValues]:
        """Create Google OAuth credentials for the Google Docs datasource integration.

        The backend's token_manager._refresh_token() always refreshes with
        config.GOOGLE_OAUTH_CLIENT_ID/SECRET (not the integration's own client), so a
        refresh_token we supply can never be refreshed by the backend. We therefore
        pre-fetch an access_token here and store it with expires_at = now + 3300, which
        keeps the backend's TOKEN_REFRESH_BUFFER (~300 s) check False for ~55 min so the
        backend uses our token directly and never calls its own _refresh_token().

        We deliberately do NOT hand the backend our real refresh_token. The backend's
        _refresh_token() refreshes with config.GOOGLE_OAUTH_CLIENT_ID (a different client
        than the one that issued our token); presenting our token to that mismatched
        client makes Google REVOKE it. Since this token is shared with the email
        integration, that revocation would also break the email tests. So we send only a
        placeholder refresh_token — the backend uses our pre-fetched access_token within
        the expires_at window, and its refresh job fails harmlessly against the
        placeholder, leaving the real token (used only here, with the correct client)
        untouched.

        The token is REUSED from the email integration, so the SAME refresh token backs
        both the email tests and the Google Docs tests. Read from
        /codemie/autotests/integrations/email:
          OAUTH_CLIENT_ID     → oauth.client_id      (the Google Cloud project of the client)
          OAUTH_CLIENT_SECRET → oauth.client_secret
          OAUTH_REFRESH_TOKEN → oauth.refresh_token
          GMAIL_USER_EMAIL    → email.smtp_username  (the automation Google account)

        Prerequisites for the Google Docs path to work (one-time setup, easy to miss):
          * The refresh_token must be issued by OAUTH_CLIENT_ID above and consented for
            the automation Google account with ALL three scopes:
                https://mail.google.com/                       (email tests)
                https://www.googleapis.com/auth/documents.readonly
                https://www.googleapis.com/auth/drive.readonly
          * Google Drive API AND Google Docs API must be enabled in the OAuth client's
            Cloud project; otherwise Drive/Docs reads 403, surfaced by the
            backend as a 422 "Access denied".
          * GOOGLE_DOC_URL must be readable by the automation Google account.

        IMPORTANT: this refresh token expires ~weekly (app in "Testing" status). When it
        is rotated it MUST be regenerated with ALL three scopes above, or the Google
        datasource tests break (the email tests would still pass).
        """
        client_id = CredentialsManager.get_parameter("OAUTH_CLIENT_ID")
        client_secret = CredentialsManager.get_parameter("OAUTH_CLIENT_SECRET")
        refresh_token = CredentialsManager.get_parameter("OAUTH_REFRESH_TOKEN")
        email = CredentialsManager.get_parameter("GMAIL_USER_EMAIL")

        resp = _http.post(
            "https://oauth2.googleapis.com/token",
            data={
                "grant_type": "refresh_token",
                "refresh_token": refresh_token,
                "client_id": client_id,
                "client_secret": client_secret,
            },
            timeout=30,
        )
        if not resp.ok:
            raise RuntimeError(
                f"Google token refresh failed {resp.status_code}: {resp.text}"
            )
        access_token = resp.json()["access_token"]

        expires_at = str(int(time.time()) + 3300)

        # Placeholder, NOT the real refresh_token — see docstring. Handing the backend the
        # real token would let its mismatched-client refresh job revoke it (and, since the
        # token is shared with email, break the email tests too).
        placeholder_refresh_token = "unused-placeholder-see-google_oauth_credentials"

        return [
            CredentialValues(key="refresh_token", value=placeholder_refresh_token),
            CredentialValues(key="access_token", value=access_token),
            CredentialValues(key="expires_at", value=expires_at),
            CredentialValues(key="email", value=email),
        ]

