    # Cache for AWS Parameter Store data to avoid repeated calls
    _aws_cache: Dict[str, Dict[str, Any]] = {}

    @staticmethod
    def _lookup(key: str) -> Optional[str]:
        """Return the configured value of a setting, or None if it is not configured."""
        env_value = os.getenv(key)
        if env_value is not None:
            return env_value
        # Earlier names of this setting (e.g. SMTP_USERNAME) still work from the environment.
        for old, new in KEY_ALIASES.items():
            if new == key and os.getenv(old) is not None:
                return os.getenv(old)

        config = CredentialsManager.CREDENTIAL_MAPPINGS.get(key)
        if config is None:
            return None
        return CredentialsManager._get_aws_parameter_with_path(
            config["aws_param"], config["aws_path"]
        )

    @staticmethod
    def get_parameter(key: str, default: Optional[str] = "") -> Optional[str]:
        """
        Get parameter value using configuration-driven approach.

        Priority:
        1. Environment variable (.env file, config file)
        2. AWS Parameter Store (only when enabled, with JSON path navigation)
        3. Configuration mapping default value
        4. Provided default value

        Args:
            key: The parameter key (e.g., "JIRA_URL")
            default: Default value if not found

        Returns:
            Parameter value or default
        """
        value = CredentialsManager._lookup(key)
        if value is not None:
            return value
        config = CredentialsManager.CREDENTIAL_MAPPINGS.get(key, {})
        return config.get("default", default)

    @staticmethod
    def get_required_parameter(key: str) -> str:
        """
        Get a setting that the test cannot run without.

        Raises:
            MissingRequiredSettingError: when the setting is not configured anywhere.
        """
        value = CredentialsManager._lookup(key)
        if value is None:
            raise MissingRequiredSettingError(
                f"Setting '{key}' is not configured. Set the environment variable {key}, "
                f"add it with `codemie-test-harness config`, or enable the secret store."
            )
        return value

    @staticmethod
    def _get_aws_parameter_with_path(aws_param: str, json_path: str) -> Optional[str]:
        """
        Get a value from the AWS Parameter Store JSON using a dot notation path.

        The store is opt-in (HARNESS_SECRET_STORE=aws-parameter-store). When it is not
        enabled this returns None and touches no AWS API. A missing parameter or path is
        "not configured" (None); an unreachable store raises SecretStoreError.

        Args:
            aws_param: parameter group appended to AWS_PS_PATH_PREFIX (e.g. "jira")
            json_path: Dot notation path (e.g. "jira_server.url")
        """
        config = AwsStoreConfig.from_env()
        if config is None:
            return None

        name = config.path_prefix + aws_param
        if name not in CredentialsManager._aws_cache:
            raw_value = AwsParameterStore.get_instance(config).get_parameter(name)
            try:
                CredentialsManager._aws_cache[name] = (
                    json.loads(raw_value) if raw_value else {}
                )
            except ValueError as e:
                raise SecretStoreError(
                    f"Secret store 'aws-parameter-store' (region={config.region}, "
                    f"prefix={config.path_prefix}): parameter '{name}' is not valid JSON"
                ) from e

        current = CredentialsManager._aws_cache[name]
        for part in json_path.split("."):
            if isinstance(current, dict) and part in current:
                current = current[part]
            else:
                return None
        return current

