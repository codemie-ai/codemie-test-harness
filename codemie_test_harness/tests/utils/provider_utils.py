import logging
import re
from typing import Optional, Dict, Any

import requests
from codemie_sdk import CodeMieClient
from hamcrest import assert_that, equal_to, has_key, not_

from codemie_test_harness.tests import VERIFY_SSL, API_DOMAIN
from codemie_test_harness.tests.utils.base_utils import (
    BaseUtils,
    get_random_name,
)
from codemie_test_harness.tests.utils.http_utils import RequestHandler

logger = logging.getLogger(__name__)

providers_endpoint = "/v1/providers"

# Matches names generated by get_random_name() and their derivatives (e.g. '- updated' suffix):
# 'autotest-' + 3 lowercase letters + '_' + 15 lowercase letters
TEST_PROVIDER_NAME_RE = re.compile(r"^autotest-[a-z]{3}_[a-z]{15}")


class ProviderUtils(BaseUtils):
    def __init__(self, client: CodeMieClient):
        """Initialize the provides service."""

        super().__init__(client)
        self._api = RequestHandler(API_DOMAIN, self.client.token, VERIFY_SSL)

    def provider_request_json(self, name: str = "AICE") -> dict:
        """Fetch a provider by name from the backend and return its JSON with a
        random name. Defaults to AICE, the provider exposing CodeExplorationToolkit
        + CatalogToolkit. The legacy standalone CodeAnalysisServiceProvider was
        retired in favor of this combined provider.
        """
        providers = self.list_providers().json()
        provider = next(p for p in providers if p["name"] == name)
        provider["name"] = get_random_name()
        return provider

    def send_post_request_to_providers_endpoint(
        self, request: Dict[str, Any]
    ) -> requests.Response:
        """
        Send request to provider creation endpoint without raising error for response status codes.

        Args:
            request: The provider creation request

        Returns:
            Raw response from '/v1/providers' endpoint
        """
        return self._api.post(providers_endpoint, json_data=request, stream=True)

    def send_get_request_to_providers_endpoint(
        self,
    ) -> requests.Response:
        """
        Send request to get providers endpoint.

        Returns:
            Raw response from '/v1/providers' endpoint
        """
        return self._api.get(providers_endpoint)

    def send_get_request_datasource_schemas_endpoint(
        self,
    ) -> requests.Response:
        """
        Send request to get datasource_schemas endpoint.

        Returns:
            Raw response from '/v1/providers/datasource_schemas' endpoint
        """
        return self._api.get(f"{providers_endpoint}/datasource_schemas")

    def create_provider(
        self,
    ) -> str:
        """
        Creates a provider for test.

        Returns:
            Created provider id
        """
        request_json = self.provider_request_json()
        # Ensure unique provider name to avoid conflicts
        request_json["name"] = get_random_name()

        response = self.send_post_request_to_providers_endpoint(request_json)

        return response.json()["id"]

    def list_providers(
        self,
    ) -> requests.Response:
        """
        List all providers.

        Returns:
            List of provider objects
        """
        response = self.send_get_request_to_providers_endpoint()

        return response

    def get_provider_by_id(self, provider_id: str) -> requests.Response:
        """
        Get a specific provider by ID.

        Args:
            provider_id: The provider ID

        Returns:
            Provider object
        """
        response = self._api.get(f"{providers_endpoint}/{provider_id}")

        return response

    def update_provider(
        self,
        provider_id: str,
        provider_update_payload: dict,
    ) -> requests.Response:
        """
        Update an existing provider.

        Args:
            provider_id: The provider ID to update
            provider_update_payload: request body

        Returns:
            Updated provider object
        """
        endpoint = f"{providers_endpoint}/{provider_id}"

        return self._api.put(endpoint, json_data=provider_update_payload)

    def remove_toolkit_parameters(
        self, provider_id: str, names: Optional[list] = None
    ) -> Dict[str, Any]:
        """
        Remove parameters from the first toolkit's base definition
        (`toolkit_config.parameters`) of an existing provider, via PUT.

        Datasources created from the provider keep their stored values for the
        removed parameters until the datasource is next updated.

        Args:
            provider_id: The provider ID to update
            names: Parameter names to remove; None removes every parameter
                (an empty base definition)

        Returns:
            The `toolkit_config.parameters` dict the backend reports after the update
        """
        provider = self.get_provider_by_id(provider_id).json()
        toolkits = provider["provided_toolkits"]
        parameters = toolkits[0]["toolkit_config"]["parameters"]
        removed_names = list(parameters) if names is None else list(names)
        for parameter_name in removed_names:
            parameters.pop(parameter_name)

        # Minimal request-shaped payload (mirrors
        # test_update_provider_schema_field_default_value): a fresh template
        # with just `name`/`provided_toolkits` overridden, rather than PUTing
        # back the full GET-fetched `provider` object, which carries
        # backend-managed/response-only fields a PUT does not expect.
        request_json = self.provider_request_json()
        request_json["name"] = provider["name"]
        request_json["provided_toolkits"] = toolkits
        response = self.update_provider(provider_id, request_json)

        assert_that(
            response.status_code,
            equal_to(200),
            f"Provider update removing {removed_names} was rejected: {response.text}",
        )
        updated_parameters = response.json()["provided_toolkits"][0]["toolkit_config"][
            "parameters"
        ]
        for parameter_name in removed_names:
            assert_that(
                updated_parameters,
                not_(has_key(parameter_name)),
                f"Parameter [{parameter_name}] is still declared after the provider update",
            )
        return updated_parameters

    def send_delete_provider_request(self, provider_id: str) -> requests.Response:
        """
        Delete a provider by ID.

        Args:
            provider_id: The provider ID to delete

        Returns:
            Response from delete operation
        """
        return self._api.delete(f"{providers_endpoint}/{provider_id}")

    def safe_delete_provider(self, provider_id: str) -> None:
        """Best-effort provider delete for fixture teardown: logs and swallows
        any failure instead of raising, so a cleanup problem never masks a
        real assertion failure from the test itself.
        """
        try:
            self.send_delete_provider_request(provider_id)
        except Exception as e:
            logger.warning(f"Failed to delete provider {provider_id}: {e}")

    def cleanup_test_providers(self, name_prefix: Optional[str] = None):
        """
        Clean up test providers.

        When name_prefix is provided, deletes providers whose names start with that prefix.
        Otherwise, deletes all providers whose names match the test naming pattern
        ('autotest-' + 3 lowercase letters + '_' + 15 lowercase letters,
        e.g. 'autotest-qdn_inqddvhfehottus').

        Args:
            name_prefix: Prefix to match for cleanup (uses test name pattern if None)
        """
        try:
            providers = self.list_providers()
            if name_prefix:
                test_providers = [
                    provider
                    for provider in providers.json()
                    if provider["name"].startswith(name_prefix)
                ]
            else:
                test_providers = [
                    provider
                    for provider in providers.json()
                    if TEST_PROVIDER_NAME_RE.match(provider["name"])
                ]

            for provider in test_providers:
                try:
                    response = self.send_delete_provider_request(provider["id"])
                    if response.status_code not in (204, 404):
                        logger.warning(
                            f"Unexpected status {response.status_code} deleting provider "
                            f"{provider['name']}: {response.text}"
                        )
                except Exception as e:
                    # Log but don't fail cleanup for individual provider
                    logger.error(f"Failed to delete provider {provider['name']}: {e}")

        except Exception as e:
            # Log but don't fail if cleanup encounters issues
            logger.error(f"Provider cleanup encountered an error: {e}")
